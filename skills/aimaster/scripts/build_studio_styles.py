#!/usr/bin/env python3
"""Build/check the shipped one-request Studio stylesheet from canonical CSS.

The installed package includes the generated file. Users never build it.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import tempfile


STATIC_ROOT = Path(__file__).resolve().parents[1] / "studio" / "static"
BUNDLE_PATH = Path("styles/studio-bundle.css")
MANIFEST_PATH = Path("styles/studio-bundle.manifest.json")
SOURCE_PATHS = (
    "styles/tokens.css",
    "styles/base.css",
    "styles/layout.css",
    "styles/media.css",
    "styles/scenario.css",
    "styles/step-scenario.css",
    "styles/plan.css",
    "styles/audio.css",
    "styles/assembly.css",
    "styles/positions.css",
    "styles/actions.css",
    "styles/shell.css",
    "styles/history.css",
    "styles/more-menu.css",
    "styles/chat-prompt-dialog.css",
    "styles/v2/tokens-v2.css",
    "styles/v2/board.css",
    "styles/v2/shell.css",
    "styles/v2/family.css",
)
_URL = re.compile(rb"url\(\s*(['\"]?)(.*?)\1\s*\)", re.IGNORECASE | re.DOTALL)


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _lf(data: bytes) -> bytes:
    """Git may materialize CSS/JSON with CRLF on native Windows checkout."""
    return data.replace(b"\r\n", b"\n")


def _source_bytes(static_root: Path, relative: str) -> bytes:
    path = static_root / relative
    if not path.is_file() or not path.resolve().is_relative_to(static_root.resolve()):
        raise ValueError(f"missing or escaping CSS source: {relative}")
    data = _lf(path.read_bytes())
    if b"@import" in data.lower():
        raise ValueError(f"CSS imports change bundling order: {relative}")
    for found in _URL.finditer(data):
        address = found.group(2).strip().decode("utf-8", "strict")
        if not address.startswith("/static/"):
            raise ValueError(f"CSS URL needs rebasing before bundling: {relative}")
    return data


def build_artifacts(static_root: Path = STATIC_ROOT) -> tuple[bytes, dict]:
    """Return exact deliverable bytes and provenance; keep cascade order."""
    chunks = [b"/* GENERATED by scripts/build_studio_styles.py. Edit source CSS, then --apply. */\n"]
    sources = []
    for relative in SOURCE_PATHS:
        data = _source_bytes(static_root, relative)
        sources.append({"path": relative, "bytes": len(data), "sha256": _sha256(data)})
        chunks.extend((f"\n/* SOURCE {relative} */\n".encode("utf-8"), data, b"\n"))
    bundle = b"".join(chunks)
    manifest = {"schema_version": 1, "canonical_eol": "LF", "sources": sources,
                "bundle": {"path": BUNDLE_PATH.as_posix(), "bytes": len(bundle), "sha256": _sha256(bundle)}}
    return bundle, manifest


def manifest_bytes(manifest: dict) -> bytes:
    return (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def check_artifacts(static_root: Path = STATIC_ROOT) -> bool:
    bundle, manifest = build_artifacts(static_root)
    current_bundle = static_root / BUNDLE_PATH
    current_manifest = static_root / MANIFEST_PATH
    return (current_bundle.is_file() and current_manifest.is_file()
            and _lf(current_bundle.read_bytes()) == bundle
            and _lf(current_manifest.read_bytes()) == manifest_bytes(manifest))


def _write_atomic(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, prefix=f".{path.name}.", delete=False) as handle:
        temporary = Path(handle.name)
        try:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        except BaseException:
            temporary.unlink(missing_ok=True)
            raise
    os.replace(temporary, path)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    choice = parser.add_mutually_exclusive_group(required=True)
    choice.add_argument("--check", action="store_true", help="fail if the shipped CSS/manifest is stale")
    choice.add_argument("--apply", action="store_true", help="rebuild only generated CSS/manifest")
    args = parser.parse_args(argv)
    if args.check:
        try:
            current = check_artifacts()
        except (OSError, ValueError) as error:
            parser.exit(1, f"studio CSS source error: {error}\n")
        print("studio CSS bundle in sync" if current else "studio CSS bundle is stale")
        return 0 if current else 1
    bundle, manifest = build_artifacts()
    _write_atomic(STATIC_ROOT / BUNDLE_PATH, bundle)
    _write_atomic(STATIC_ROOT / MANIFEST_PATH, manifest_bytes(manifest))
    if not check_artifacts():
        parser.exit(1, "studio CSS bundle did not round-trip\n")
    print("studio CSS bundle rebuilt")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
