/** Resolve an owned UI string. Params are used only in UI templates. */
export function t(key, params = {}, language = typeof document === 'undefined' ? 'ru' : document.documentElement?.lang || 'ru') {
  const source = language === 'en' ? EN.get(key) || key : key;
  return source.replace(/\{([a-z_]+)\}/g, (_, name) => String(params[name] ?? ''));
}
