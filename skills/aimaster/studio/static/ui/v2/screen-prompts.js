// Тексты запросов агенту, нужные только экранам Сценарий / Кадры /
// Сборка. Общие тексты (референсы, ещё вариант, промпт, файл) живут в
// `chat-prompts.js` — здесь их не дублируем, а дописываем недостающее.
// Чистые функции: возвращают `{title, prompt}` и ничего не открывают.

import { projectRef } from "./chat-prompts.js";

const MODE_WORDS = Object.freeze({
  per_scene: "кадр за кадром",
  one_shot: "одним заходом",
});

/** Переключатель «Как делаем ролик» — смена режима идёт через агента. */
export function changeGenMode(project, revision, mode) {
  const word = MODE_WORDS[mode] || mode;
  return {
    title: `Как делаем ролик: ${word}`,
    prompt: `Открой ${projectRef(project, revision)}. Я хочу делать ролик ${word} (gen_mode «${mode}»). `
      + `Сначала объясни, что при этом станет с позициями и промптами и что придётся переделать, `
      + `и дождись моего подтверждения. После него переключи режим штатной командой Creator Studio. `
      + `Ничего не генерируй.`,
  };
}

/** «Изменить сценарий → чат». */
export function editScenario(project, revision, version) {
  const which = version?.version_id ? ` Сейчас активна версия version_id «${version.version_id}».` : "";
  return {
    title: "Изменить сценарий",
    prompt: `Открой ${projectRef(project, revision)}. Нужно изменить текст сценария.${which} `
      + `Спроси, что именно поправить, покажи новый текст целиком и только после моего подтверждения `
      + `запиши новую версию сценария штатной командой Creator Studio. Раскадровку сам не переписывай.`,
  };
}

/** «Вернуться к сценарию → чат» с уже пройденного шага. */
export function reopenScenario(project, revision) {
  return {
    title: "Вернуться к сценарию",
    prompt: `Открой ${projectRef(project, revision)}. Я хочу вернуться к сценарию. `
      + `Сначала перечисли, какие шаги и результаты при этом придётся проходить заново, `
      + `и дождись моего подтверждения. После него верни проект на сценарий штатной командой `
      + `Creator Studio (reopen-scenario). Ничего не удаляй и не генерируй.`,
  };
}

/** «Собрать → чат» на экране «Сборка». */
export function assembleFinal(project, revision, { ready = false } = {}) {
  return {
    title: ready ? "Пересобрать ролик" : "Собрать ролик",
    prompt: `Открой ${projectRef(project, revision)}. ${ready ? "Нужно пересобрать финальный ролик." : "Нужно собрать финальный ролик."} `
      + `Проверь принятые клипы, слои звука и длительность, покажи план сборки и дождись моего подтверждения — `
      + `это платное действие. Недостающие материалы ничем не подменяй: честно скажи, чего не хватает.`,
  };
}
