// Вход дашборда. Одна развилка и больше ничего: по умолчанию грузится
// новая оболочка (`ui/v2/`), а старая открывается по требованию — её код
// целиком лежит в `app-v1.js` и до приёмки перестройки не удаляется
// (правило «вытесненное удаляем после приёмки»).
//
// Почему два написания переключателя. Сервер пускает на `/` ровно один
// параметр запроса, и только `project` (studio/http_app.py, `_path`):
// `?project=…&ui=v1` он отвечает 400 ещё до того, как страница начнёт
// грузиться. Поэтому рабочее написание — якорь `#ui=v1`, который
// браузер серверу вообще не отправляет; `?ui=v1` тоже распознаётся и
// заработает само, если список разрешённых параметров когда-нибудь
// расширят. Менять сервер ради переключателя в этой волне не стали.
//
// Обе ветки — динамический импорт: модуль, который не выбран, не
// загружается и ничего не подписывает на `document`.

const url = new URL(window.location.href);
const legacy = url.searchParams.get("ui") === "v1"
  || new URLSearchParams(url.hash.replace(/^#/, "")).get("ui") === "v1";

if (legacy) {
  import("./app-v1.js");
} else {
  import("./ui/v2/boot.js").then((module) => module.bootV2());
}
